from docx import Document
from datetime import datetime

def generate_markdown_export(report: dict) -> str:
    """Generates a markdown string containing the rewritten resume."""
    sections = report["resume"].get("sections", {})
    rewrites = report.get("rewrites", {})
    
    md_content = f"# Resume Draft - {datetime.now().strftime('%Y-%m-%d')}\n\n"
    
    # We loop through all available sections. If there's a rewrite, use it. Otherwise, use original.
    options = list(sections.keys()) or ["summary", "experience", "skills", "projects", "education"]
    
    for section in options:
        md_content += f"## {section.replace('_', ' ').upper()}\n\n"
        if section in rewrites:
            md_content += "> 🪄 *AI Rewritten Version*\n\n"
            md_content += rewrites[section].get("text", "") + "\n\n"
        else:
            md_content += sections.get(section, "") + "\n\n"
            
    md_content += "---\n*Generated by RoastMyResume locally.*"
    return md_content

def generate_docx_export(report: dict) -> bytes:
    """Generates a docx file in memory containing the rewritten resume."""
    from io import BytesIO
    doc = Document()
    doc.add_heading(f"Resume Draft - {datetime.now().strftime('%Y-%m-%d')}", 0)
    
    sections = report["resume"].get("sections", {})
    rewrites = report.get("rewrites", {})
    options = list(sections.keys()) or ["summary", "experience", "skills", "projects", "education"]
    
    for section in options:
        doc.add_heading(section.replace("_", " ").upper(), level=1)
        if section in rewrites:
            p = doc.add_paragraph("🪄 AI Rewritten Version:")
            p.runs[0].italic = True
            doc.add_paragraph(rewrites[section].get("text", ""))
        else:
            doc.add_paragraph(sections.get(section, ""))
            
    file_stream = BytesIO()
    doc.save(file_stream)
    file_stream.seek(0)
    return file_stream.read()
